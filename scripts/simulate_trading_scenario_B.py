# simulate_trading_scenario_C.py
import json
import os
import random
from web3 import Web3
import pandas as pd

base_path = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
build_path = os.path.join(base_path, "build")
results_path = os.path.join(base_path, "results")
data_path = os.path.join(base_path, "data")



# Load data
with open(os.path.join(data_path, "fixed_demand.json"), "r") as f:
    consumer_demand = json.load(f)
with open(os.path.join(data_path, "fixed_solar_profile.json"), "r") as f:
    fixed_solar_profile = json.load(f)
with open(os.path.join(data_path, "accounts.json"), "r") as f:
    accounts = json.load(f)

prosumer_accounts = accounts[:20]
consumer_accounts = accounts[20:]



# dynamic government pricing
total_hourly_demand = [sum(float(consumer_demand[c][h]) for c in consumer_demand) for h in range(24)]
min_d = min(total_hourly_demand)
max_d = max(total_hourly_demand)
normalized_demand = [(d - min_d) / (max_d - min_d) for d in total_hourly_demand]

def get_government_price(hour):
    base_price = 0.12  # $0.12/kWh
    peak_price = 0.32  # $0.32/kWh
    return round(base_price + (peak_price - base_price) * normalized_demand[hour], 4)

# --- Parameters ---
HOURS = 24
hourly_logs = []
energy_gen_prosumer={acc["address"]: 0.0 for acc in prosumer_accounts}
energy_supplied_pTg={acc["address"]: 0.0 for acc in prosumer_accounts}
energy_supplied_pTc={acc["address"]: 0.0 for acc in prosumer_accounts}
grid_energy_supplied_to_customers= {acc["address"]: 0.0 for acc in consumer_accounts}
revenue_rec_pFg={acc["address"]: 0.0 for acc in prosumer_accounts}
revenue_rec_pFc={acc["address"]: 0.0 for acc in prosumer_accounts}
revenue_paid_c2g= {acc["address"]: 0.0 for acc in consumer_accounts}
revenue_paid_c2p={acc["address"]: 0.0 for acc in prosumer_accounts}
# --- Start Simulation ---
print("\n🔁 Starting Scenario B simulation (Prosumers → Govt → Consumers)...\n")

for hour in range(HOURS):
    print(f"🕒 Hour {hour}")


    # Step 1: Prosumers generate and sell to government
    for prosumer in prosumer_accounts:
        addr = prosumer["address"]
        generation = fixed_solar_profile[hour]
        if generation > 0:
            gov_buy_price = get_government_price(hour) *0.5  # 50% of selling price
            revenue_rec_pFg[addr] += generation * gov_buy_price
            energy_supplied_pTg[addr] += generation

            hourly_logs.append({
                "hour": hour,
                "prosumer_address": addr,
                "energy_supplied_p2g": generation,
                "revenue_rec_pFg": generation*gov_buy_price,
            })

    # Step 2: Consumers buy from government
    for consumer in consumer_accounts:
        addr = consumer["address"]
        demand = float(consumer_demand[addr][hour])
        if demand <= 0:
            continue

        gov_price = get_government_price(hour)
        usd_cost = demand * gov_price
        revenue_paid_c2g[addr] += usd_cost
        grid_energy_supplied_to_customers[addr] += demand


        hourly_logs.append({
            "hour": hour,
            "consumer_address": addr,
            "demand_kwh": demand,
            "price_usd": gov_price,
            "usd_cost": usd_cost,
            "energy_from_gov": demand,
        })

print("\n Scenario B Simulation complete.\n")
print(f" Energy generated by Prosumers: {sum(energy_supplied_pTg.values()):.2f} kWh")
print(f" Energy supplied by Prosumers to government: {sum(energy_supplied_pTg.values()):.2f} kWh")
print(f" Energy supplied by Prosumers to customers: NA")
print(f" Grid Energy supplied to customers: {(sum(grid_energy_supplied_to_customers.values())-sum(energy_supplied_pTg.values())):.2f} kWh")
print(f" Revenue received by prosumers from government :{sum(revenue_rec_pFg.values()):.2f} USD")
print(f" Revenue received by prosumers from customers : NA")
print(f" Revenue paid by customers to government  : {sum(revenue_paid_c2g.values()):.2f} USD")

# --- Save Summary Results ---
summary = []

# Consumers: total USD paid to government
for acc in consumer_accounts:
    summary.append({
        "address": acc["address"],
        "role": "consumer",
        "total_cost_usd": round(revenue_paid_c2g[acc["address"]], 2)
    })

# Prosumers: total USD received from government
for acc in prosumer_accounts:
    summary.append({
        "address": acc["address"],
        "role": "prosumer",
        "total_revenue_usd": round(revenue_rec_pFg[acc["address"]], 2)
    })

# Save to CSV
pd.DataFrame(summary).to_csv(os.path.join(results_path, "scenario_B_summary.csv"), index=False)

# --- Save Hourly Logs ---
pd.DataFrame(hourly_logs).to_csv(os.path.join(results_path, "scenario_B_hourly_log.csv"), index=False)

print("📁 Results saved to:")
print("   scenario_B_summary.csv")
print("   scenario_B_hourly_log.csv")

